"""
benchmarks/common/report.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Result dataclasses and the markdown renderer for ``project-management/BENCHMARKS.md``.

Every report is stamped with exactly what produced the numbers (dataset
size, embedding provider, judge, model where applicable) — the same
reproducibility discipline ai-agent-platform-competitive-analysis.md asks of
the vendor figures it cites. A number in this report with no caveat means
"reproduce this on your own data before trusting it for a decision," same as
that document's own disclaimer.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any


@dataclass
class RunMetadata:
    run_id: str
    embedding_provider: str
    embedding_dim: int
    generated_at: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(timespec="seconds")
    )


@dataclass
class CategoryScore:
    category: str
    correct: int
    total: int

    @property
    def accuracy(self) -> float:
        return (self.correct / self.total) if self.total else 0.0


@dataclass
class RetrievalQualityResult:
    judge_name: str
    embedding_provider: str
    top_k: int
    category_scores: list[CategoryScore]
    is_longmemeval_comparable: bool
    deviation_notes: list[str]

    @property
    def overall_correct(self) -> int:
        return sum(c.correct for c in self.category_scores)

    @property
    def overall_total(self) -> int:
        return sum(c.total for c in self.category_scores)

    @property
    def overall_accuracy(self) -> float:
        return (self.overall_correct / self.overall_total) if self.overall_total else 0.0


@dataclass
class BaselineResult:
    """Flat-context (no SDK) baseline result from ``run_baseline()``.

    The judge receives all session turns concatenated directly — no
    ``remember()``, no ``search()``.  Compared side-by-side with
    :class:`RetrievalQualityResult` to measure the value the SDK's
    structured memory store + vector retrieval adds over a plain
    long-context prompt.
    """

    judge_name: str
    category_scores: list[CategoryScore]

    @property
    def overall_correct(self) -> int:
        return sum(c.correct for c in self.category_scores)

    @property
    def overall_total(self) -> int:
        return sum(c.total for c in self.category_scores)

    @property
    def overall_accuracy(self) -> float:
        return (self.overall_correct / self.overall_total) if self.overall_total else 0.0


@dataclass
class LatencyCostResult:
    remember_summary: dict[str, Any]
    search_summary: dict[str, Any]
    hook_summaries: dict[str, dict[str, Any]]  # e.g. {"consolidator": {...}}
    hook_configured: bool


@dataclass
class IsolationLoadResult:
    tenants: int
    agents_per_tenant: int
    concurrent_workers: int
    ops_per_worker: int
    total_write_ops: int
    total_read_assertions: int
    leakage_incidents: int
    elapsed_s: float

    @property
    def passed(self) -> bool:
        return self.leakage_incidents == 0


def render_markdown(
    metadata: RunMetadata,
    retrieval: RetrievalQualityResult | None = None,
    baseline: BaselineResult | None = None,
    latency: LatencyCostResult | None = None,
    isolation: IsolationLoadResult | None = None,
) -> str:
    lines: list[str] = []
    lines.append("# agent-memory-sdk — Benchmark Report")
    lines.append("")
    lines.append(
        "Generated by `scripts/run_benchmarks.py` (see `benchmarks/README.md` for how to "
        "reproduce). This report is **not** produced by CI — it requires a live Db2 instance "
        "and, for the retrieval-quality suite, an `EmbeddingProvider`/LLM judge, and is run on "
        "demand via `make benchmark`."
    )
    lines.append("")
    lines.append("## Run metadata")
    lines.append("")
    lines.append(f"- **Generated at:** {metadata.generated_at}")
    lines.append(f"- **Run id:** `{metadata.run_id}`")
    lines.append(
        f"- **Embedding provider:** {metadata.embedding_provider} (dim={metadata.embedding_dim})"
    )
    lines.append("")

    if retrieval is not None:
        lines.append("## 1. Retrieval quality (LongMemEval-shaped)")
        lines.append("")
        lines.append(f"- **Judge:** {retrieval.judge_name}")
        lines.append(f"- **Embedding provider:** {retrieval.embedding_provider}")
        lines.append(f"- **top_k:** {retrieval.top_k}")
        lines.append(f"- **Dataset size:** {retrieval.overall_total} questions")
        lines.append("")
        if retrieval.is_longmemeval_comparable:
            lines.append(
                "**Methodology:** matches the LongMemEval (arXiv 2410.10813) ability-category "
                "shape and an LLM-judge verdict. Treat as comparable to vendor-reported "
                "LongMemEval figures **only** after reviewing the judge/embedding config above "
                "against the vendor's reported config — sample size here is a synthetic smoke "
                "dataset, not the full 500-question LongMemEval benchmark."
            )
        else:
            lines.append(
                "> ⚠️ **Methodology deviation — NOT a LongMemEval-comparable number.** "
                "This run used one or more fallback components (a non-semantic embedding "
                "provider and/or a keyword-overlap judge instead of an LLM judge). The dataset "
                "shape follows LongMemEval's five ability categories, but the score below "
                "reflects lexical overlap, not a real correctness judgment. Do **not** cite this "
                "number next to Oracle's 93.8%, Zep's DMR/LongMemEval figures, or any other "
                "vendor-reported LongMemEval score in ai-agent-platform-competitive-analysis.md. "
                "Re-run with `--embedding-provider sentence-transformers` (or `ollama`) and "
                "`--judge ollama` (or `--judge ollama:<model>`) for a number that means anything."
            )
        for note in retrieval.deviation_notes:
            lines.append(f"> - {note}")
        lines.append("")
        lines.append("| Category | Correct | Total | Accuracy |")
        lines.append("|---|---|---|---|")
        for cat in retrieval.category_scores:
            lines.append(
                f"| {cat.category} | {cat.correct} | {cat.total} | {cat.accuracy:.1%} |"
            )
        lines.append(
            f"| **Overall** | **{retrieval.overall_correct}** | **{retrieval.overall_total}** "
            f"| **{retrieval.overall_accuracy:.1%}** |"
        )
        lines.append("")

    if baseline is not None:
        lines.append("### With-SDK vs. without-SDK comparison")
        lines.append("")
        lines.append(
            f"Judge: `{baseline.judge_name}`. "
            "**With SDK**: session turns stored via `remember()`, answer retrieved via "
            "`search()`. **Without SDK (baseline)**: all session turns concatenated "
            "into a flat context window, no storage or retrieval."
        )
        lines.append("")
        # Build per-category comparison if SDK result is also present.
        if retrieval is not None:
            sdk_by_cat = {s.category: s for s in retrieval.category_scores}
            base_by_cat = {s.category: s for s in baseline.category_scores}
            lines.append("| Category | With SDK | Without SDK | Delta |")
            lines.append("|---|---|---|---|")
            for cat in sdk_by_cat:
                s = sdk_by_cat[cat]
                b = base_by_cat.get(cat)
                sdk_acc = s.accuracy
                base_acc = b.accuracy if b else 0.0
                delta = sdk_acc - base_acc
                lines.append(
                    f"| {cat} | {sdk_acc:.1%} ({s.correct}/{s.total}) "
                    f"| {base_acc:.1%} ({b.correct if b else 0}/{b.total if b else 0}) "
                    f"| **{delta:+.1%}** |"
                )
            sdk_oa = retrieval.overall_accuracy
            base_oa = baseline.overall_accuracy
            delta_oa = sdk_oa - base_oa
            lines.append(
                f"| **Overall** | **{sdk_oa:.1%}** ({retrieval.overall_correct}/{retrieval.overall_total}) "
                f"| **{base_oa:.1%}** ({baseline.overall_correct}/{baseline.overall_total}) "
                f"| **{delta_oa:+.1%}** |"
            )
        else:
            # Baseline-only run (no SDK result in this report).
            lines.append("| Category | Without SDK | Total |")
            lines.append("|---|---|---|")
            for cat in baseline.category_scores:
                lines.append(f"| {cat.category} | {cat.accuracy:.1%} | {cat.total} |")
            lines.append(
                f"| **Overall** | **{baseline.overall_accuracy:.1%}** "
                f"| **{baseline.overall_total}** |"
            )
        lines.append("")

    if latency is not None:
        lines.append("## 2. Latency / cost")
        lines.append("")
        lines.append("### Per-call latency")
        lines.append("")
        lines.append("| Operation | Count | Mean (ms) | p50 (ms) | p95 (ms) | p99 (ms) | Max (ms) |")
        lines.append("|---|---|---|---|---|---|---|")
        for summary in (latency.remember_summary, latency.search_summary):
            if summary.get("count", 0) == 0:
                lines.append(f"| {summary.get('label', '?')} | 0 | — | — | — | — | — |")
                continue
            lines.append(
                f"| {summary['label']} | {summary['count']} | {summary['mean_ms']} | "
                f"{summary['p50_ms']} | {summary['p95_ms']} | {summary['p99_ms']} | {summary['max_ms']} |"
            )
        lines.append("")
        lines.append("### Per-turn LLM cost")
        lines.append("")
        if not latency.hook_configured:
            lines.append(
                "No Consolidator/Reconciler/Summarizer hook was configured for this run — the "
                "no-op default path. **Estimated LLM cost: $0.00, 0 hook calls.** This is the "
                "comparison point against passive-extraction-pipeline competitors (Mem0, "
                "Bedrock, LangMem) in ai-agent-platform-competitive-analysis.md: this SDK's "
                "write path only calls an LLM when a caller explicitly configures one."
            )
        else:
            for hook_name, summary in latency.hook_summaries.items():
                lines.append(f"- **{hook_name}:** {summary}")
        lines.append("")

    if isolation is not None:
        verdict = "✅ PASS — zero cross-scope leakage" if isolation.passed else "❌ FAIL — leakage detected"
        lines.append("## 3. Isolation under load")
        lines.append("")
        lines.append(f"- **Verdict:** {verdict}")
        lines.append(f"- **Synthetic tenants:** {isolation.tenants}")
        lines.append(f"- **Agents per tenant:** {isolation.agents_per_tenant}")
        lines.append(f"- **Concurrent workers:** {isolation.concurrent_workers}")
        lines.append(f"- **Ops per worker:** {isolation.ops_per_worker}")
        lines.append(f"- **Total write operations:** {isolation.total_write_ops}")
        lines.append(f"- **Total read assertions (search/list_all):** {isolation.total_read_assertions}")
        lines.append(f"- **Cross-scope leakage incidents:** {isolation.leakage_incidents}")
        lines.append(f"- **Elapsed:** {isolation.elapsed_s:.2f}s")
        lines.append("")
        lines.append(
            "This exercises the same `MemoryScope`-bound-parameter isolation boundary VER-5 "
            "verified with mocked cursors in a single-threaded unit test — here, under real "
            "concurrent load against a live Db2 instance. A leakage count of 0 across many "
            "concurrent writers/readers is the actual measurement the governed-substrate SWOT "
            "claim in ai-agent-platform-competitive-analysis.md depends on; run again with "
            "larger `--tenants`/`--workers` for stronger evidence before citing this in "
            "marketing materials."
        )
        lines.append("")

    lines.append("---")
    lines.append(
        "*Caveat, matching the discipline of ai-agent-platform-competitive-analysis.md: numbers "
        "in this report come from a synthetic dataset and a specific local configuration. They "
        "are reproducible (rerun `scripts/run_benchmarks.py` with the same flags) but are not "
        "independently audited and should not be treated as a substitute for evaluating this SDK "
        "against your own workload.*"
    )
    lines.append("")
    return "\n".join(lines)
