#!/usr/bin/env python3
"""
scripts/render_results_summary.py
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
Read one or more ``results.jsonl`` files (shared benchmark envelope schema)
and render a consolidated Markdown or HTML summary grouped by suite.

Usage
-----
::

    # Markdown → $GITHUB_STEP_SUMMARY
    python scripts/render_results_summary.py \
        consolidated/benchmark/results.jsonl \
        consolidated/locust-isolation/results.jsonl \
        --run-number "$GITHUB_RUN_NUMBER" \
        --sha "$GITHUB_SHA" \
        >> "$GITHUB_STEP_SUMMARY"

    # HTML
    python scripts/render_results_summary.py results.jsonl --html > report.html

Exit codes
----------
0 — always (prints a "no results" message if no files are found).

stdlib only — no third-party dependencies.
"""

from __future__ import annotations

import argparse
import html as html_module
import json
import sys
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path

# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def _load_records(paths: list[Path]) -> list[dict]:
    """Read all JSONL records from *paths*, skipping missing/malformed files."""
    records: list[dict] = []
    for path in paths:
        if not path.exists():
            print(f"render_results_summary: {path} not found — skipping.", file=sys.stderr)
            continue
        try:
            with path.open(encoding="utf-8") as fh:
                for lineno, line in enumerate(fh, 1):
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        records.append(json.loads(line))
                    except json.JSONDecodeError as exc:
                        print(
                            f"render_results_summary: {path}:{lineno} — JSON parse error: {exc}",
                            file=sys.stderr,
                        )
        except OSError as exc:
            print(f"render_results_summary: cannot read {path}: {exc}", file=sys.stderr)
    return records


# ---------------------------------------------------------------------------
# Markdown output
# ---------------------------------------------------------------------------

_STATUS_ICON = {"pass": "✅ pass", "fail": "❌ fail", "skipped": "⏭️ skipped"}


def _render_markdown(records: list[dict], run_number: str, sha: str, ref: str) -> str:
    lines: list[str] = []
    lines.append("## Consolidated Benchmark Results")
    lines.append("")

    meta_parts: list[str] = []
    if run_number:
        meta_parts.append(f"**Run:** `{run_number}`")
    if sha:
        meta_parts.append(f"**Commit:** `{sha[:12]}`")
    if ref:
        meta_parts.append(f"**Ref:** `{ref}`")
    if meta_parts:
        lines.append("  ".join(meta_parts))
        lines.append("")

    if not records:
        lines.append("> No benchmark envelope records found.")
        return "\n".join(lines)

    lines.append("| Suite | Metric | Value | Unit | Status |")
    lines.append("|:------|:-------|------:|:-----|:-------|")

    by_suite: dict[str, list[dict]] = defaultdict(list)
    for rec in records:
        by_suite[rec.get("suite", "unknown")].append(rec)

    for suite in sorted(by_suite):
        for rec in by_suite[suite]:
            status_raw = rec.get("status", "")
            status_display = _STATUS_ICON.get(status_raw, status_raw)
            value = rec.get("value", "")
            # Format floats to a reasonable precision
            if isinstance(value, float):
                value = f"{value:.3f}".rstrip("0").rstrip(".")
            lines.append(
                f"| {suite} "
                f"| {rec.get('metric', '')} "
                f"| {value} "
                f"| {rec.get('unit', '')} "
                f"| {status_display} |"
            )

    lines.append("")
    lines.append(
        "_Generated by `render_results_summary.py` — shared envelope schema._"
    )
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# HTML output
# ---------------------------------------------------------------------------

_HTML_TEMPLATE = """\
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>agent-memory-sdk — unified benchmark results</title>
  <style>
    *, *::before, *::after {{ box-sizing: border-box; }}
    body {{ font-family: -apple-system, "Segoe UI", system-ui, sans-serif;
           font-size: 14px; line-height: 1.6; color: #1f2328;
           background: #ffffff; margin: 0; padding: 24px; }}
    .container {{ max-width: 900px; margin: 0 auto; }}
    h1 {{ font-size: 1.4rem; font-weight: 600; margin-bottom: 4px; }}
    .meta {{ color: #57606a; font-size: 13px; margin-bottom: 20px; }}
    .meta span {{ margin-right: 16px; }}
    table {{ border-collapse: collapse; width: 100%; font-size: 13px; }}
    thead tr {{ background: #f7f8fa; }}
    th {{ padding: 8px 10px; text-align: left; border-bottom: 2px solid #e5e7eb;
         font-weight: 600; white-space: nowrap; }}
    th.num {{ text-align: right; }}
    td {{ padding: 7px 10px; border-bottom: 1px solid #e5e7eb; }}
    td.num {{ text-align: right; font-family: "SFMono-Regular", Consolas, monospace;
              font-size: 12px; }}
    tr:hover {{ background: #f7f8fa; }}
    .pass {{ color: #1a7f37; }}
    .fail {{ color: #cf222e; }}
    .skipped {{ color: #57606a; }}
    .empty {{ color: #57606a; font-style: italic; }}
    footer {{ margin-top: 40px; padding-top: 12px; border-top: 1px solid #e5e7eb;
              font-size: 12px; color: #57606a; text-align: center; }}
  </style>
</head>
<body>
<div class="container">
  <h1>Unified Benchmark Results</h1>
  <div class="meta">
    {meta_spans}
    <span>Generated {generated_at}</span>
  </div>
  <table>
    <thead>
      <tr>
        <th>Suite</th>
        <th>Metric</th>
        <th class="num">Value</th>
        <th>Unit</th>
        <th>Status</th>
      </tr>
    </thead>
    <tbody>
{table_rows}
    </tbody>
  </table>
  <footer>Made with IBM Bob &bull; agent-memory-sdk benchmarks</footer>
</div>
</body>
</html>
"""

_HTML_STATUS_CLASS = {"pass": "pass", "fail": "fail", "skipped": "skipped"}
_HTML_STATUS_LABEL = {"pass": "✅ pass", "fail": "❌ fail", "skipped": "⏭️ skipped"}


def _render_html(records: list[dict], run_number: str, sha: str, ref: str) -> str:
    meta_parts: list[str] = []
    if run_number:
        meta_parts.append(f'<span>Run <strong>#{html_module.escape(run_number)}</strong></span>')
    if sha:
        meta_parts.append(f'<span>Commit <code>{html_module.escape(sha[:12])}</code></span>')
    if ref:
        meta_parts.append(f'<span>Branch <code>{html_module.escape(ref)}</code></span>')
    meta_spans = "\n    ".join(meta_parts)
    generated_at = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    if not records:
        table_rows = '      <tr><td colspan="5" class="empty">No benchmark envelope records found.</td></tr>'
    else:
        tr_lines: list[str] = []
        by_suite: dict[str, list[dict]] = defaultdict(list)
        for rec in records:
            by_suite[rec.get("suite", "unknown")].append(rec)
        for suite in sorted(by_suite):
            for rec in by_suite[suite]:
                status_raw = rec.get("status", "")
                css_class = _HTML_STATUS_CLASS.get(status_raw, "")
                label = _HTML_STATUS_LABEL.get(status_raw, html_module.escape(status_raw))
                value = rec.get("value", "")
                if isinstance(value, float):
                    value = f"{value:.3f}".rstrip("0").rstrip(".")
                tr_lines.append(
                    f'      <tr>'
                    f'<td>{html_module.escape(suite)}</td>'
                    f'<td>{html_module.escape(rec.get("metric", ""))}</td>'
                    f'<td class="num">{html_module.escape(str(value))}</td>'
                    f'<td>{html_module.escape(rec.get("unit", ""))}</td>'
                    f'<td class="{css_class}">{label}</td>'
                    f'</tr>'
                )
        table_rows = "\n".join(tr_lines)

    return _HTML_TEMPLATE.format(
        meta_spans=meta_spans,
        generated_at=generated_at,
        table_rows=table_rows,
    )


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(
        description="Render a consolidated summary from shared-schema results.jsonl files.",
    )
    parser.add_argument(
        "inputs",
        nargs="*",
        metavar="RESULTS_JSONL",
        help="One or more results.jsonl files to merge.",
    )
    parser.add_argument(
        "--html",
        action="store_true",
        help="Produce a self-contained HTML report instead of Markdown.",
    )
    parser.add_argument("--run-number", default="", help="GitHub Actions run number.")
    parser.add_argument("--sha", default="", help="Git commit SHA.")
    parser.add_argument("--ref", default="", help="Git ref name (branch/tag).")
    parser.add_argument("--run-id", default="", help="GitHub Actions run ID (unused, accepted for compatibility).")
    args = parser.parse_args()

    paths = [Path(p) for p in (args.inputs or [])]
    records = _load_records(paths)

    if args.html:
        print(_render_html(records, args.run_number, args.sha, args.ref))
    else:
        print(_render_markdown(records, args.run_number, args.sha, args.ref))

    sys.exit(0)


if __name__ == "__main__":
    main()
